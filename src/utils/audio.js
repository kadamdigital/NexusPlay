let audioCtx = null;
let isMuted = false;

// Initialize or resume AudioContext safely upon user interaction
function getAudioContext() {
  if (typeof window === 'undefined') return null;
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

export function setAudioMuted(muted) {
  isMuted = muted;
  try {
    localStorage.setItem('nexus_audio_muted', JSON.stringify(muted));
  } catch (e) {
    console.warn('Could not persist audio setting', e);
  }
}

export function getAudioMuted() {
  try {
    const saved = localStorage.getItem('nexus_audio_muted');
    if (saved !== null) {
      isMuted = JSON.parse(saved);
    }
  } catch (e) {
    // fallback
  }
  return isMuted;
}

